import type { Reciter, Surah } from '../types/quran';

function padNumber(num: number): string {
  return String(num).padStart(3, '0');
}

function defaultAudioUrl(surahNumber: number): string {
  return `https://server8.mp3quran.net/afs/${padNumber(surahNumber)}.mp3`;
}

function makeSurah(
  id: number,
  nameArabic: string,
  versesCount: number,
  nameEnglish: string,
  isMeccan: boolean,
): Surah {
  return {
    number: id,
    nameArabic,
    versesCount,
    audioUrl: defaultAudioUrl(id),
    nameEnglish,
    isMeccan,
    revelationTypeArabic: isMeccan ? 'مكية' : 'مدنية',
    paddedNumber: padNumber(id),
  };
}

